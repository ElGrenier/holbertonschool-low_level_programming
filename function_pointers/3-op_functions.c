#include "3-calc.h"
/**
 * op_add - add 2 value
 * @a: value a
 * @b: value b
 * Return: result
 */
int op_add(int a, int b)
{
	return a + b;
}
/**
 * op_sub - substract 2 value
 * @a: value a
 * @b: value b
 * Return: result
 */
int op_sub(int a, int b)
{
	return a - b;
}
/**
 * op_mul - multiplicate 2 value
 * @a: value a
 * @b: value b
 * Return: result
 */
int op_mul(int a, int b)
{
	return a * b;
}
/**
 * op_div - divise 2 value
 * @a: value a
 * @b: value b
 * Return: result
 */
int op_div(int a, int b)
{
	return a / b;
}
/**
 * op_mod - modulo 2 value
 * @a: value a
 * @b: value b
 * Return: result
 */
int op_mod(int a, int b)
{
	return a % b;
}